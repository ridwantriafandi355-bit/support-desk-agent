// Workflow 3: Email intake (IMAP) -> Support Desk Agent
// =====================================================================
const intakeCode = `${banner('Turn new emails into tickets for the Support Desk Agent. Skips our own mail and bounces.')}
const cfg = $('Intake config').first().json;
let identities = {};
try { identities = JSON.parse(cfg.demo_identities || '{}'); } catch (e) { identities = {}; }
const lower = s => String(s || '').trim().toLowerCase();

function sender(j) {
  const v = j.from && j.from.value && j.from.value[0];
  if (v) return { email: v.address || '', name: v.name || '' };
  const raw = String(j.from || '');
  const m = raw.match(/<([^>]+)>/);
  return { email: m ? m[1] : raw.trim(), name: raw.replace(/<[^>]+>/, '').replace(/"/g, '').trim() };
}

function cleanBody(j) {
  let t = j.text || j.textPlain || String(j.html || j.textHtml || '').replace(/<[^>]+>/g, ' ');
  t = String(t).replace(/\\r/g, '');
  const cut = t.search(/^(On .+wrote:|-----Original Message-----|Pada .+menulis:)/m);
  if (cut > 0) t = t.slice(0, cut);
  return t.split('\\n').filter(l => !l.startsWith('>')).join('\\n').trim();
}

const out = [];
for (const item of $('Email inbox (IMAP)').all()) {
  const j = item.json;
  const from = sender(j);
  const subject = String(j.subject || '');
  if (!from.email || lower(from.email) === lower(cfg.store_email)) continue;
  // Safety for demos on a personal inbox: only process allow-listed senders when a list is set.
  const allowed = String(cfg.allowed_senders || '').split(',').map(lower).filter(Boolean);
  if (allowed.length && !allowed.includes(lower(from.email))) continue;
  if (/mailer-daemon|no-?reply|postmaster/i.test(from.email)) continue;
  const identity = identities[lower(from.email)] || from.email;
  out.push({ json: { payload: {
    id: 'EM-' + Date.now() + '-' + out.length,
    received_at: new Date(j.date || Date.now()).toISOString(),
    from_name: from.name,
    from_email: identity,
    reply_to: from.email,
    subject,
    body: cleanBody(j),
    channel: 'email',
    message_id: j.messageId || null,
    options: { dry_run: cfg.live_mode !== true },
  } } });
}
return out;
`;

function buildIntake(S) {
  idCounter = 200;
  // With an allow-list, the IMAP search itself only fetches unread mail FROM those senders,
  // so nothing else in the mailbox is read or marked as read.
  const senders = String(S.allowed_senders || '').split(',').map(s => s.trim()).filter(Boolean);
  const search = senders.length === 1 ? ['UNSEEN', ['FROM', senders[0]]]
    : senders.length > 1 ? ['UNSEEN', senders.slice(1).reduce((acc, s) => ['OR', acc, ['FROM', s]], ['FROM', senders[0]])]
    : null;
  const trigger = withCred({
    parameters: { mailbox: S.intake_mailbox, postProcessAction: 'read', format: 'resolved', options: search ? { customEmailConfig: JSON.stringify(search) } : {} },
    id: nid(), name: 'Email inbox (IMAP)', type: 'n8n-nodes-base.emailReadImap', typeVersion: 2.2, position: [0, 0],
  }, S.creds, 'imap');
  return {
    id: 'sdaEmailIntake01',
    name: 'Email Intake (IMAP -> Support Desk Agent)',
    active: false,
    nodes: [
      sticky('## Email intake\nPolls the support inbox over IMAP and sends each new email to the Support Desk Agent webhook.\n\nKeeping intake separate means the agent works with any channel: add a Zendesk, form or WhatsApp intake the same way.\n\n`demo_identities` maps a real test sender to a fictional customer so the demo can use the fake order data.', [-320, -320], 300, 300, 4),
      trigger,
      {
        parameters: {
          mode: 'manual',
          assignments: { assignments: [
            { id: 'in-1', name: 'agent_url', value: 'http://localhost:5678/webhook/support/ticket', type: 'string' },
            { id: 'in-2', name: 'store_email', value: S.store_email, type: 'string' },
            { id: 'in-3', name: 'demo_identities', value: S.demo_identities, type: 'string' },
            { id: 'in-4', name: 'live_mode', value: S.live_mode, type: 'boolean' },
            { id: 'in-5', name: 'allowed_senders', value: S.allowed_senders || '', type: 'string' },
          ] },
          includeOtherFields: false,
          options: {},
        },
        id: nid(), name: 'Intake config', type: 'n8n-nodes-base.set', typeVersion: 3.4, position: [220, 0],
        executeOnce: true,
      },
      code('Email -> ticket', [440, 0], intakeCode),
      {
        parameters: {
          method: 'POST',
          url: "={{ $('Intake config').first().json.agent_url }}",
          sendBody: true,
          specifyBody: 'json',
          jsonBody: '={{ JSON.stringify($json.payload) }}',
          options: { timeout: 180000 },
        },
        id: nid(), name: 'Send to Support Desk Agent', type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position: [660, 0],
        onError: 'continueRegularOutput',
      },
    ],
    connections: conn({
      'Email inbox (IMAP)': ['Intake config'],
      'Intake config': ['Email -> ticket'],
      'Email -> ticket': ['Send to Support Desk Agent'],
    }),
    settings: { executionOrder: 'v1' },
    pinData: {},
  };
}

