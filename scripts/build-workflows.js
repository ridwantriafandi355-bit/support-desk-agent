const parseTriageCode = `${banner('Validate the AI triage output. Anything invalid becomes an error, which the rules send to a human.')}
${constSrc('INTENTS', engine.INTENTS)}
${constSrc('RISK_FLAGS', engine.RISK_FLAGS)}
${fnSrc(engine.normalizeOrderNumber, engine.extractOrderNumber, engine.pickOrderNumber)}

const { triage_request, ...state } = $('${N.normalize}').first().json;
const res = $input.first().json;
const errors = [];
let triage;
try {
  if (res.error) throw new Error(typeof res.error === 'string' ? res.error : (res.error.message || JSON.stringify(res.error)));
  const content = res.choices && res.choices[0] && res.choices[0].message && res.choices[0].message.content;
  if (!content) throw new Error('Empty triage response');
  triage = JSON.parse(content);
  if (!INTENTS.includes(triage.intent)) throw new Error('Invalid intent: ' + triage.intent);
  triage.risk_flags = (Array.isArray(triage.risk_flags) ? triage.risk_flags : []).filter(f => RISK_FLAGS.includes(f));
  triage.confidence = Number(triage.confidence);
} catch (e) {
  errors.push({ step: 'triage', message: String(e.message || e).slice(0, 500) });
  triage = { error: String(e.message || e).slice(0, 500) };
}

const lookup_number = triage.error
  ? extractOrderNumber(state.ticket.subject + ' ' + state.ticket.body)
  : pickOrderNumber(state.ticket, triage);

return [{ json: { ...state, triage, lookup_number, usage: { triage: res.usage || null }, errors } }];
`;

