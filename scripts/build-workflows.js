const root = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');

const orders = JSON.parse(read('data/orders.json'));
const catalog = JSON.parse(read('data/catalog.json'));
const policies = read('data/policies.md').trim();
const catalogText = catalog.map(p => `- ${p.name} (SKU ${p.sku}), $${p.price_usd}: ${p.facts.join('; ')}.`).join('\n');

const engineSource = read('src/policy-engine.js')
  .replace(/\/\/ @export-start[\s\S]*?\/\/ @export-end/, '')
  .trim();
const fnSrc = (...fns) => fns.map(f => f.toString()).join('\n\n');
const constSrc = (name, value) => `const ${name} = ${JSON.stringify(value, null, 2)};`;
const banner = title => `// ${title}\n// GENERATED by scripts/build-workflows.js from src/. Edit the source files, then rebuild.\n`;

// ---------- node helpers ----------
let idCounter = 0;
const nid = () => `sda-node-${String(++idCounter).padStart(3, '0')}`;
// Local builds disable nodes whose credential doesn't exist yet, so the workflow can still be published.
let DISABLE_MISSING = false;
const withCred = (node, creds, type) => {
  if (creds && creds[type]) return { ...node, credentials: { [type]: creds[type] } };
  return DISABLE_MISSING ? { ...node, disabled: true } : node;
};

const code = (name, position, jsCode, extra = {}) => ({
  parameters: { jsCode }, id: nid(), name, type: 'n8n-nodes-base.code', typeVersion: 2, position, ...extra,
});

const noop = (name, position) => ({ parameters: {}, id: nid(), name, type: 'n8n-nodes-base.noOp', typeVersion: 1, position });

const sticky = (content, position, width, height, color) => ({
  parameters: { content, width, height, color }, id: nid(), name: `Note ${idCounter + 1}`,
  type: 'n8n-nodes-base.stickyNote', typeVersion: 1, position,
});

const ifTrue = (name, position, leftValue, operation = 'true') => ({
  parameters: {
    conditions: {
      options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 2 },
      conditions: [{ id: `${name}-cond`, leftValue, rightValue: '', operator: { type: 'boolean', operation, singleValue: true } }],
      combinator: 'and',
    },
    options: {},
  },
  id: nid(), name, type: 'n8n-nodes-base.if', typeVersion: 2.2, position,
});

const conn = (map) => {
  const out = {};
  for (const [from, outputs] of Object.entries(map)) {
    out[from] = { main: outputs.map(targets => (Array.isArray(targets) ? targets : [targets]).filter(Boolean).map(node => ({ node, type: 'main', index: 0 }))) };
  }
  return out;
};

