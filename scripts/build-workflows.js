const parseDraftCode = `${banner('Validate the AI draft, then run the second guard (knowledge gap or ungrounded details -> human review).')}
${fnSrc(engine.findUngrounded, engine.applyDraftGuard)}

const { draft_request, draft_sources, ...state } = $('${N.policy}').first().json;
const res = $input.first().json;
const errors = state.errors.slice();
let draft;
try {
  if (res.error) throw new Error(typeof res.error === 'string' ? res.error : (res.error.message || JSON.stringify(res.error)));
  const content = res.choices && res.choices[0] && res.choices[0].message && res.choices[0].message.content;
  if (!content) throw new Error('Empty draft response');
  draft = JSON.parse(content);
  if (typeof draft.reply !== 'string' || draft.reply.trim().length < 20) throw new Error('Draft reply missing or too short');
  draft.kb_gap = draft.kb_gap === true;
  draft.ungrounded = findUngrounded(draft.reply, draft_sources);
} catch (e) {
  errors.push({ step: 'draft', message: String(e.message || e).slice(0, 500) });
  draft = { error: String(e.message || e).slice(0, 500) };
}

const decision = applyDraftGuard(state.decision, draft, draft_sources);
return [{ json: { ...state, draft, decision, usage: { ...state.usage, draft: res.usage || null }, errors } }];
`;

const resultCode = `${banner('Shape the result and compute latency + estimated AI cost for this ticket.')}
const s = $input.first().json;
const cfg = s.config;
const u = s.usage || {};
const costOf = (usage, priceIn, priceOut) => usage ? ((usage.prompt_tokens || 0) * priceIn + (usage.completion_tokens || 0) * priceOut) / 1e6 : 0;
const cost = costOf(u.triage, cfg.triage_price_in, cfg.triage_price_out) + costOf(u.draft, cfg.draft_price_in, cfg.draft_price_out);
const tokens = usage => usage ? { prompt: usage.prompt_tokens || 0, completion: usage.completion_tokens || 0 } : null;

const NEXT_STEP = {
  auto_reply: 'Send the AI reply to the customer',
  needs_approval: 'Send the AI draft to a reviewer (approve / edit / reject)',
  human_handoff: 'Assign to a human agent' + (s.decision.priority === 'urgent' ? ' immediately (URGENT)' : ''),
  ignore: 'Archive without replying',
};

return [{ json: {
  ticket_id: s.ticket.id,
  action: s.decision.action,
  priority: s.decision.priority,
  next_step: NEXT_STEP[s.decision.action],
  dry_run: s.options.dry_run,
  reasons: s.decision.reasons,
  triage: s.triage,
  order_match: s.decision.order_match,
  facts: s.decision.facts,
  draft: s.draft || null,
  ticket: { id: s.ticket.id, from_name: s.ticket.from_name, from_email: s.ticket.from_email, reply_to: s.ticket.reply_to, subject: s.ticket.subject },
  store: { email: cfg.store_email, name: cfg.store_name, telegram_chat_id: String(cfg.telegram_chat_id) },
  metrics: {
    latency_ms: Date.now() - s.t0,
    tokens: { triage: tokens(u.triage), draft: tokens(u.draft) },
    est_cost_usd: Number(cost.toFixed(6)),
  },
  errors: s.errors,
} }];
`;

const applyDecisionCode = `${banner('Turn the reviewer form into a decision: send (as written or edited) or not.')}
const r = $('${N.result}').first().json;
const form = $input.first().json || {};
const choice = String(form['Decision'] || '');
const text = String(form['Reply to send'] || '').trim();
const original = (r.draft && r.draft.reply ? r.draft.reply : '').trim();

let outcome = 'timed_out';
if (choice.startsWith('Send')) outcome = text === original ? 'approved' : 'edited';
else if (choice) outcome = 'rejected';

const send = (outcome === 'approved' || outcome === 'edited') && text.length > 0;
return [{ json: { ...r, review: { outcome, send, reply_text: send ? text : null } } }];
`;

